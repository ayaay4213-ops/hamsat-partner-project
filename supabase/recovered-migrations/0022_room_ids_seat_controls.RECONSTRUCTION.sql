alter table public.rooms
  add column if not exists public_id bigint generated by default as identity;
create unique index if not exists rooms_public_id_key on public.rooms(public_id);

alter table public.rooms
  add column if not exists seat_limit integer not null default 10;

do $block$
begin
  if not exists (
    select 1 from pg_constraint
     where conrelid = 'public.rooms'::regclass
       and conname = 'rooms_seat_limit_check'
  ) then
    alter table public.rooms
      add constraint rooms_seat_limit_check check (seat_limit between 1 and 10);
  end if;
end;
$block$;

create table if not exists public.room_seats (
  room_id uuid not null references public.rooms(id) on delete cascade,
  seat_no smallint not null check (seat_no between 1 and 10),
  user_id uuid not null references auth.users(id) on delete cascade,
  seated_at timestamptz not null default now(),
  primary key (room_id, seat_no),
  unique (room_id, user_id)
);

create index if not exists room_seats_user_id_idx
  on public.room_seats(user_id);

alter table public.room_seats enable row level security;

drop policy if exists "Room members can view microphone seats" on public.room_seats;
create policy "Room members can view microphone seats"
  on public.room_seats for select to authenticated
  using (private.is_room_member(room_id));

