-- HAMSAT 0086: persist in-app feedback and expose it only to administrators.
create table if not exists public.user_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  feedback_type text not null check (feedback_type in ('اقتراح','مشكلة تقنية','شكوى')),
  body text not null check (char_length(btrim(body)) between 5 and 1500),
  status text not null default 'new' check (status in ('new','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now()
);

create index if not exists idx_user_feedback_created_at
  on public.user_feedback (created_at desc);
create index if not exists idx_user_feedback_user_created_at
  on public.user_feedback (user_id, created_at desc);

alter table public.user_feedback enable row level security;
revoke all on table public.user_feedback from anon, authenticated;
grant select on table public.user_feedback to authenticated;

drop policy if exists "Admins read user feedback" on public.user_feedback;
create policy "Admins read user feedback"
on public.user_feedback
for select
to authenticated
using (is_admin());

create or replace function public.submit_user_feedback(p_type text, p_body text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user uuid := (select auth.uid());
  v_id bigint;
begin
  if v_user is null then raise exception 'يجب تسجيل الدخول'; end if;
  if p_type is null or p_type not in ('اقتراح','مشكلة تقنية','شكوى') then
    raise exception 'نوع الملاحظة غير صالح';
  end if;
  if char_length(btrim(coalesce(p_body,''))) < 5
     or char_length(btrim(coalesce(p_body,''))) > 1500 then
    raise exception 'يجب أن تكون الملاحظة بين 5 و1500 حرف';
  end if;

  insert into public.user_feedback(user_id,feedback_type,body)
  values(v_user,p_type,btrim(p_body))
  returning id into v_id;

  return v_id;
end;
$function$;

revoke all on function public.submit_user_feedback(text,text) from public, anon, authenticated;
grant execute on function public.submit_user_feedback(text,text) to authenticated;


create or replace function public.admin_update_user_feedback(p_feedback_id bigint, p_status text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if coalesce(public.is_admin(), false) is not true then
    raise exception 'هذه العملية متاحة للمشرفة الرئيسية فقط';
  end if;
  if p_status is null or p_status not in ('new','reviewing','resolved','dismissed') then
    raise exception 'حالة الملاحظة غير صالحة';
  end if;

  update public.user_feedback
     set status = p_status
   where id = p_feedback_id;

  return found;
end;
$function$;

revoke all on function public.admin_update_user_feedback(bigint,text) from public, anon, authenticated;
grant execute on function public.admin_update_user_feedback(bigint,text) to authenticated;
